from nornref import canonjson, cbor, enrollreq, entry, fixture, note, replay, trust


#: Every path this run has written, so stale files can be pruned afterwards.
_written: set[pathlib.Path] = set()


def write(path: pathlib.Path, data: bytes | str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data if isinstance(data, bytes) else data.encode("utf-8"))
    _written.add(path.resolve())


#: Top-level paths this generator owns, and may therefore delete stale files
#: from. Everything else under `testdata/vectors` belongs to somebody else.
OWNED = frozenset({
    "keys.json", "entries", "log", "genesis", "state.json",
    "trust.cbor", "trust.toml", "trust.fingerprint", "trust-bad", "trust-good",
    "receipt.note", "receipt.json", "receipt-bad", "requests", "requests-bad", "policies",
    "entries-hostile", "proven", "log-empty", "log-admission", "log-cas", "log-edges", "log-order", "genesis-good",
    "receipt-rotated",
})

#: Produced by `make vectors-log` from the Go implementation, because building
#: a tiled log requires one (SPEC §12, the suite's two provenances). Pruning
#: them here deleted them silently -- eleven files -- until this was scoped.
FOREIGN = frozenset({"served-empty-entry", "served-large-bad", "served-rotated-wrong-name", "served-rotated-earlier", "served", "served-large", "proofs", "fork", "checkpoints-bad", "served-rotated",
                    "proofs-bad", "served-bad", "served-superseded",
                    "served-twice-cosigned", "served-extra-witness",
                    "served-name-collision", "served-unknown-algorithm", "served-stranger-name", "detect",
                    "served-genesis", "proofs-rotated"})

#: Not generated by anything here.
#:
#: `anchors` holds a `.ots` proof written by `python-opentimestamps` -- the
#: reference implementation of a format neither of Norn's implementations owns.
#: Regenerating it would defeat its purpose: it is in the suite precisely
#: because somebody else's code produced the bytes.
#: `ed25519-cctv` is fetched upstream; only its separate flag table is derived here.
KEEP = frozenset({"README.md", "anchors", "SHA256SUMS", "ed25519-cctv"})


def prune(out: pathlib.Path) -> list[pathlib.Path]:
    """Delete files under OWNED that this run did not write.

    Without this, a renumbering leaves orphans that sort *between* live entries,
    so an implementer globbing the directory loads a different log than the
    manifest describes. Returns what was removed.
    """
    unclaimed = {p.name for p in out.iterdir()} - OWNED - FOREIGN - KEEP
    if unclaimed:
        raise SystemExit(
            f"unclaimed vector paths: {', '.join(sorted(unclaimed))}. Add each to "
            "OWNED (this generator prunes it) or FOREIGN (another one owns it); "
            "a path in neither escapes pruning and rots.")

    removed = []
    for name in sorted(OWNED):
        root = out / name
        for path in sorted([root] if root.is_file() else root.rglob("*")):
            if not path.is_file() or path.name in KEEP:
                continue
            if path.resolve() not in _written:
                path.unlink()
                removed.append(path)
    for name in sorted(OWNED):
        root = out / name
        if not root.is_dir():
            continue
        for folder in sorted(root.rglob("*"), reverse=True):
            if folder.is_dir() and not any(folder.iterdir()):
                folder.rmdir()
    return removed


def write_keys(out: pathlib.Path) -> None:
    doc = {
        "comment": "TEST KEYS. Seeds are SHA-256('norn/testvector/v1\\n' + name); "
                   "WireGuard keys are X25519 from SHA-256(prefix + 'wg/' + name).",
        "ed25519": {
            name: {"seed": k.seed, "public": k.public, "kid": k.id}
            for name, k in sorted(fixture.KEYS.items())
        },
        "x25519": {name: pk for name, pk in sorted(fixture.WG.items())},
        "net": fixture.NET,
    }
    write(out / "keys.json", canonjson.dumps(doc) + "\n")


def write_entries(out: pathlib.Path) -> None:
    for name, env in fixture.catalogue():
        raw = entry.encode(env)
        write(out / "entries" / f"{name}.cbor", raw)
        write(out / "entries" / f"{name}.json", canonjson.dumps({
            "entry": env,
            "entry_hash": entry.entry_hash(raw),
            "leaf_hash": entry.leaf_hash(raw),
            "preimage_sha256": hashlib.sha256(entry.preimage(env)).digest(),
            "size": len(raw),
        }) + "\n")


def write_log(out: pathlib.Path) -> None:
    """The replay fixture: the log, its manifest, and the state it produces."""
    items = fixture.log()
    raw = [item.raw for item in items]
    for item in items:
        write(out / "log" / f"{item.name}.cbor", item.raw)
        if item.reason:
            write(out / "log" / f"{item.name}.reason", item.reason + "\n")

    anchor = fixture.anchor_for(raw)
    write(out / "log" / "manifest.json", canonjson.dumps({
        "anchor": {"net": anchor.net, "genesis_hash": anchor.genesis_hash, "log_key": anchor.log_key, "policy": anchor.policy},
        "entries": [{"index": i, "name": it.name, "reason": it.reason or ""}
                    for i, it in enumerate(items)],
    }) + "\n")
    final = replay.replay(anchor, raw)
    write(out / "state.json", final.to_json() + "\n")
    write_proven(out, final, raw)


def write_proven(out: pathlib.Path, final: Any, entries: list[bytes]) -> None:
    """The proven set at four evaluation times (SPEC §5.3).

    `state.json` is deliberately clock-independent, so until this existed the
    suite had no vector for expiry at all -- the rule that decides when a
    device stops being admitted to the network. Cold gate run 5 named it the
    one gap with a direct production consequence.

    The deadlines are read from the state rather than written down: a fixture
    that hardcodes an instant stops testing the boundary the moment the entry
    behind it changes.
    """
    from nornref.state import grant_from_label
    labels = [final.devices[name]["labels"]["ip"] for name in ("router", "badgrant")]
    labels.append("::ffff:10.0.0.1/128")
    cases = [{"label": label, "grant": grant_from_label(label), "says": says}
             for label, says in zip(labels, (
                 "duplicates removed, sorted as text",
                 "does not parse **as a whole** is **no grant**",
                 "An IPv4-mapped IPv6 prefix is no grant either"))]
    # D-077's expected grants come from the grammar, so the table can catch
    # a library accepting another form instead of certifying its own output.
    syntax = "A part is `<address>/<length>` and nothing else"
    zero = "place of the length, a zone, a leading zero, any other whitespace or any other"
    mask = "A bare address, a netmask or hostmask in"
    whitespace = "any other whitespace or any other"
    space = "U+0020 is removed from both of its ends and nothing else is."
    canonical = "every group in lowercase hexadecimal (an embedded dotted quad is written as"
    forms = [
        ("9.0.0.0/8, 10.0.0.0/8", ["10.0.0.0/8", "9.0.0.0/8"], "duplicates removed, sorted as text"),
        ("2001:db8:0:1:1:1:1:1/128", ["2001:db8:0:1:1:1:1:1/128"], "IPv6 address in RFC 5952 form with"),
        ("2001:db8:0:0:1:1:1:1/128", ["2001:db8::1:1:1:1/128"], "IPv6 address in RFC 5952 form with"),
        ("10.9.1.5", [], mask),
        ("10.9.1.0/024", [], zero),
        ("010.9.1.0/24", [], zero),
        ("10.9.1.0/255.255.255.0", [], mask),
        ("10.9.1.0/0.0.0.255", [], mask),
        ("fe80::1%eth0/64", [], "bits, and no zone."),
        *[(char + "10.9.1.0/24", [], whitespace)
          for char in ("\t", "\r", "\v", "\u001c", "\u001f", "\u0085",
                       "\u00a0", "\u200b", "\u3000")],
        ("10.9.1.0/24 ", ["10.9.1.0/24"], space),
        (" 10.9.1.0/24 ,fd00::5/64", ["10.9.1.0/24", "fd00::/64"], space),
        ("10.9.1/24", [], "dotted quad — four decimal octets 0–255, none with a leading zero"),
        ("1.2.3.4/33", [], "The length is decimal without a leading zero, at most 32"),
        ("fd00::5/129", [], "for a dotted quad and 128 for IPv6."),
        ("10.9.1.0/+24", [], "The length is decimal without a leading zero, at most 32"),
        ("1.2.3.4/", [], syntax),
        ("/24", [], syntax),
        ("10.9.1.0/24,", [], syntax),
        ("", [], syntax),
        ("FD00::5/64", ["fd00::/64"], canonical),
        ("fd00:0000::5/64", ["fd00::/64"], canonical),
        ("fd00:00000::5/64", [], "address as RFC 4291 §2.2 writes it: groups of one to four hexadecimal digits in"),
        ("64:ff9b::10.0.0.1/96", ["64:ff9b::/96"], canonical),
        ("64:ff9b::10.0.0.1/128", ["64:ff9b::a00:1/128"], canonical),
        ("1.2.3.4/0", ["0.0.0.0/0"], "The grant is each masked prefix in"),
        ("::/0", ["::/0"], "The grant is each masked prefix in"),
        ("::ffff:10.0.0.1/0", [], "An IPv4-mapped IPv6 prefix is no grant either"),
    ]
    cases.extend({"label": label, "grant": grant, "says": says}
                 for label, grant, says in forms)
    write(out / "proven" / "grant-labels.json", canonjson.dumps({
        "comment": "SPEC 4.0 grant derivation as a pure function of label text; D-077 grammar, U+0020 trim and canonical masked text (cold gate run 14, H1).",
        "cases": cases,
    }) + "\n")

    deadlines = sorted({d["expires"] for d in final.devices.values()
                        if d["status"] == "active" and d.get("expires")})
    if not deadlines:
        raise SystemExit("no active device has an expiry; the proven fixture would prove nothing")
    deadline = deadlines[0]

    cases = [
        (0, "no-clock",
         "no instant satisfies the witness policy, so expiry is not judged at all"),
        (deadline - 1, "before-the-deadline", "one second before it expires"),
        (deadline, "at-the-deadline",
         "expires == T has passed: the boundary two implementations disagree about"),
        (deadline + 1, "after-the-deadline", "one second after"),
    ]
    # Cold gate run 11, D14. §8.1's condition 3 says replay must yield the
    # device "active with that `wg_pk`" and never says whose. Nothing joined a
    # bundle to a proven set, so a reader that required the BUNDLE's key --
    # and therefore dropped every device that has ever rotated -- passed the
    # whole suite. This states, per active device, the entry its bundle proves
    # and both keys, so the two readings can be told apart.
    #
    # The facts come from the replay, not from the .bundle files: those are
    # written by the Go generator, so a reader checking one against the other
    # is checking two implementations against each other.
    bundles = {}
    for name, dev in sorted(final.devices.items()):
        if dev["status"] != "active":
            continue
        at = dev["since_index"]
        enrolled = _wg_pk_of(entries[at])
        # `wg_pk` is bytes in the in-memory state and hex only once it is
        # serialised, so both sides are normalised before they are compared --
        # comparing a hex string with bytes silently reports every device as
        # rotated, which is a case that separates nothing.
        current = _as_hex(dev["wg_pk"])
        rotated = enrolled != current
        bundles[name] = {
            "file": f"proofs/{name}.bundle",
            "proves_index": at,
            "bundle_wg_pk": enrolled,
            "state_wg_pk": current,
            "rotated_since": rotated,
            "says": (
                "condition 3 is about the `wg_pk` REPLAY yields -- the key this "
                "node will install -- not the one the bundle's own entry carries. "
                + ("`" + name + "` rotated after it was enrolled, so the two "
                   "differ and this case separates the two readings: it MUST be "
                   "proven, on the replayed key. A reader that requires the "
                   "bundle's key drops it, and drops every device that ever "
                   "rotates, which is routine."
                   if rotated else
                   "`" + name + "` never rotated, so both keys agree and this "
                   "case cannot separate the readings. It is here so the set is "
                   "complete rather than curated.")),
        }

    write(out / "proven" / "cases.json", canonjson.dumps({
        "comment": "the devices a node admits at evaluation time `t` (SPEC §5.3). "
                   "`t` is the checkpoint's quorum time, never a wall clock, and "
                   "t = 0 means there is no clock at all. A device is expired "
                   "exactly when expires != 0 and expires <= t. `bundles` joins "
                   "each active device to the §8.1 proof bundle that proves it, "
                   "and gives both keys, because condition 3 means the replayed "
                   "one and the fixture is the only thing that says so",
        "cases": [{"name": name, "t": t, "why": why, "proven": final.proven(t)}
                  for t, name, why in cases],
        "bundles": bundles,
        # D-073: every active device's grant, which the evaluation time does
        # not change. `router` is the masked-and-sorted case, `badgrant` the
        # label that does not parse as a whole, `nas` the device with none.
        "grants": {name: final.grant(name) for name, dev in sorted(final.devices.items())
                   if dev["status"] == "active"},
    }) + "\n")


def _as_hex(value: bytes | str) -> str:
    """Lowercase hex, whether the value arrived as bytes or already encoded."""
    return value.hex() if isinstance(value, (bytes, bytearray)) else value


def _wg_pk_of(raw: bytes) -> str:
    """The WireGuard key an entry establishes, as lowercase hex.

    An `enroll` carries it inside the embedded request (SPEC §4.3); a `rotate`
    carries it in the body.
    """
    body = cbor.decode(raw)["body"]
    if "request" in body:
        return cbor.decode(body["request"])["wg_pk"].hex()
    return body["wg_pk"].hex()


