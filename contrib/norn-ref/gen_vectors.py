def write_trust(out: pathlib.Path) -> None:
    """The trust anchor, its human rendering, its fingerprint, and a receipt."""
    doc = fixture.trust_file()
    trust.validate(doc)
    write(out / "trust.cbor", trust.encode(doc))
    write(out / "trust.toml", trust.to_toml(doc))
    write(out / "trust.fingerprint", trust.fingerprint(doc) + "\n")

    genesis_leaf = doc["genesis_hash"]
    deadline = fixture.T0 + 60  # params.mmd
    text = note.receipt_text(doc["origin"], genesis_leaf, deadline)
    signed = note.sign(text, doc["origin"], fixture.KEYS["logkey"])
    write(out / "receipt.note", signed)
    write(out / "receipt.json", canonjson.dumps({
        "comment": "receipt for the genesis entry; verifies under trust.log_key",
        "origin": doc["origin"],
        "leaf_hash": genesis_leaf,
        "deadline": deadline,
        "text_sha256": __import__("hashlib").sha256(text.encode()).digest(),
    }) + "\n")

    # Cold gate run 11, D4. §7 showed the deadline as a bare <uint> with no
    # canonicality rule and no vector, while §6 is emphatic that the
    # checkpoint's size line has exactly one spelling -- so `ReceiptDeadlineLax`
    # passed all 622 checks. A receipt is "non-repudiable proof of log
    # misbehaviour", which means two parties will one day compare two copies of
    # one, and a number with two spellings is a comparison with two answers.
    #
    good_text = note.receipt_text(doc["origin"], genesis_leaf, deadline)
    cases = []
    rules = {}
    codes = {}

    def add_case(name: str, text: str, code: str, says: str,
                 *, signer: str = "logkey", malformed: bool = False,
                 raw_signed: str | None = None,
                 now_unix: int | None = None) -> None:
        # Framing negatives cannot be re-signed: the defect is in the signature
        # block terminator itself. Every body/signature negative is signed over
        # its altered content by the named log key unless it tests trust lookup.
        if malformed:
            signed_case = text
        elif raw_signed is not None:
            signed_case = raw_signed
        else:
            signed_case = note.sign(text, doc["origin"], fixture.KEYS[signer])
        write(out / "receipt-bad" / name, signed_case)
        case = {"name": name, "says": says}
        if now_unix is not None:
            case["now_unix"] = now_unix
        cases.append(case)
        rules[name] = {"section": "7", "says": says}
        codes[name] = code

    # Note framing is tested before any trusted signature lookup.
    add_case("extra-final-newline.note", signed + "\n", "note",
             "a second `0x0A` after the final signature creates a forbidden blank line",
             malformed=True)

    # Same receipt text, signed by a key other than the one in trust.cbor: a
    # reader holding only that file trusts no other key (§7, §9.4).
    add_case("untrusted-log-key.note", good_text, "log-signature",
             "The note MUST verify under a log key the verifier trusts", signer="logkey2")

    body_lines = good_text.splitlines()
    add_case("fifth-line.note", good_text + "extra\n", "receipt",
             "Require exactly four signed-text lines")
    changed = body_lines.copy()
    changed[1] = changed[1][:5] + changed[1][5].upper() + changed[1][6:]
    add_case("origin-case-changed.note", "\n".join(changed) + "\n", "origin",
             "The origin line MUST equal the anchored origin")

    changed = body_lines.copy()
    changed[0] = "norn/receipt/v2"
    add_case("wrong-header.note", "\n".join(changed) + "\n", "receipt",
             "The first line MUST be")

    changed = body_lines.copy()
    changed[1] = "norn/elsewhere"
    add_case("wrong-origin.note", "\n".join(changed) + "\n", "origin",
             "The origin line MUST equal the anchored origin")

    changed = body_lines.copy()
    changed[2] = "!!!!"
    add_case("bad-leaf-hash.note", "\n".join(changed) + "\n", "leaf-hash",
             "The leaf hash MUST be standard base64 and decode to exactly 32 bytes")

    # The 32-byte hash ends in one '=' and has two unused pad bits. Change only
    # those bits, then re-sign the text so signature verification still passes.
    changed = body_lines.copy()
    alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    leaf_text = changed[2]
    if len(leaf_text) != 44 or not leaf_text.endswith("="):
        raise ValueError("fixture leaf hash must be 32-byte standard base64")
    last = alphabet.index(leaf_text[-2])
    if last % 4 != 0:
        raise ValueError("fixture leaf hash is not canonical base64")
    changed[2] = leaf_text[:-2] + alphabet[last + 1] + "="
    if base64.b64decode(changed[2], validate=True) != base64.b64decode(leaf_text, validate=True):
        raise ValueError("pad-bit mutation changed the leaf hash")
    add_case("leaf-hash-nonzero-pad-bits.note", "\n".join(changed) + "\n", "leaf-hash",
             "unused pad bits in the leaf hash MUST be zero")

    # Cold gate run 13, D18: the same hash with its padding dropped. It decodes
    # to the right 32 bytes for a lenient reader, and re-encoding does not give
    # the line back, so it is `leaf-hash`.
    changed = body_lines.copy()
    changed[2] = leaf_text[:-1]
    add_case("leaf-hash-unpadded.note", "\n".join(changed) + "\n", "leaf-hash",
             "The leaf hash MUST be standard base64 and decode to exactly 32 bytes")

    # D-076 bounds every decimal note line at the signed integer maximum.
    changed = body_lines.copy()
    changed[3] = "9223372036854775808"
    add_case("deadline-above-2-63.note", "\n".join(changed) + "\n", "deadline",
             "at most 2⁶³−1")

    # The same receipt with one leading zero, re-signed so only its spelling is
    # wrong. `ParseUint` alone accepts this second representation.
    changed = body_lines.copy()
    changed[3] = "0" + changed[3]
    add_case("leading-zero.note", "\n".join(changed) + "\n", "deadline",
             "The deadline MUST be canonical decimal")

    changed = body_lines.copy()
    changed[2] = base64.b64encode(hashlib.sha256(b"a different entry").digest()).decode("ascii")
    add_case("different-entry.note", "\n".join(changed) + "\n", "entry",
             "the submitted entry's leaf hash MUST equal the receipt's leaf hash")

    # Expiry is a relation between the receipt and the caller's supplied time;
    # carry that time in the case instead of changing an otherwise good note.
    add_case("expired-at-deadline.note", signed, "expired",
             "A nonzero checking time at or after the deadline MUST refuse the receipt",
             raw_signed=signed, now_unix=deadline)

    # Cold gate run 13, D4. Every case above fails one step, so a reader that
    # swapped two adjacent steps refused each for the same reason and passed.
    # Each below fails a step and the one after it, re-signed (the first by the
    # wrong key, which is its earlier fault), so only the order decides. Each
    # cites the rule of the step that decides it.
    def two_faults(**lines: str) -> str:
        changed = body_lines.copy()
        for index, value in lines.items():
            changed[int(index[1:])] = value
        return "\n".join(changed) + "\n"

    foreign_leaf = base64.b64encode(hashlib.sha256(b"a different entry").digest()).decode("ascii")
    add_case("order-log-signature-before-receipt.note", two_faults(l0="norn/receipt/v2"),
             "log-signature", "The note MUST verify under a log key the verifier trusts", signer="logkey2")
    add_case("order-receipt-before-origin.note",
             two_faults(l0="norn/receipt/v2", l1="norn/elsewhere"), "receipt",
             "The first line MUST be")
    add_case("order-origin-before-leaf-hash.note",
             two_faults(l1="norn/elsewhere", l2="!!!!"), "origin",
             "The origin line MUST equal the anchored origin")
    add_case("order-leaf-hash-before-deadline.note",
             two_faults(l2="!!!!", l3="0" + body_lines[3]), "leaf-hash",
             "The leaf hash MUST be standard base64 and decode to exactly 32 bytes")
    add_case("order-deadline-before-entry.note",
             two_faults(l2=foreign_leaf, l3="0" + body_lines[3]), "deadline",
             "The deadline MUST be canonical decimal")
    add_case("order-entry-before-expired.note", two_faults(l2=foreign_leaf),
             "entry", "the submitted entry's leaf hash MUST equal the receipt's leaf hash",
             now_unix=deadline)

    write(out / "receipt-bad" / "cases.json", canonjson.dumps({
        "comment": "receipt refusal vectors in §7 check order. Body and signer "
                   "negatives are re-signed; extra-final-newline is malformed note "
                   "framing and expired-at-deadline uses the explicit time in its case. "
                   "Each order- case fails two adjacent steps and MUST be refused for "
                   "the earlier, whose rule it cites",
        "cases": cases,
        "rules": rules,
        "codes": codes,
    }) + "\n")


