#!/usr/bin/env python3
"""Generate testdata/vectors from the reference implementation.

Usage: python3 contrib/norn-ref/gen_vectors.py testdata/vectors

Every file written here is a contract the Go implementation must satisfy. Run
`make vectors` after changing the reference, and review the diff: a changed
vector means a changed protocol.
"""

from __future__ import annotations

import pathlib
import sys

import hashlib

from nornref import canonjson, enrollreq, entry, fixture, note, replay, trust


#: Every path this run has written, so stale files can be pruned afterwards.
_written: set[pathlib.Path] = set()


def write(path: pathlib.Path, data: bytes | str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data if isinstance(data, bytes) else data.encode("utf-8"))
    _written.add(path.resolve())


#: Top-level paths this generator owns, and may therefore delete stale files
#: from. Everything else under `testdata/vectors` belongs to somebody else.
OWNED = frozenset({
    "keys.json", "entries", "log", "genesis", "state.json",
    "trust.cbor", "trust.toml", "trust.fingerprint", "trust-bad", "trust-good",
    "receipt.note", "receipt.json", "requests", "requests-bad", "policies",
    "entries-hostile", "proven", "log-empty",
})

#: Produced by `make vectors-log` from the Go implementation, because building
#: a tiled log requires one (SPEC §12, the suite's two provenances). Pruning
#: them here deleted them silently -- eleven files -- until this was scoped.
FOREIGN = frozenset({"served", "proofs", "fork", "checkpoints-bad", "served-rotated",
                    "proofs-bad", "served-bad", "served-superseded",
                    "served-twice-cosigned", "detect"})

#: Not generated by anything here.
#:
#: `anchors` holds a `.ots` proof written by `python-opentimestamps` -- the
#: reference implementation of a format neither of Norn's implementations owns.
#: Regenerating it would defeat its purpose: it is in the suite precisely
#: because somebody else's code produced the bytes.
KEEP = frozenset({"README.md", "anchors", "SHA256SUMS"})


def prune(out: pathlib.Path) -> list[pathlib.Path]:
    """Delete files under OWNED that this run did not write.

    Without this, a renumbering leaves orphans that sort *between* live entries,
    so an implementer globbing the directory loads a different log than the
    manifest describes. Returns what was removed.
    """
    unclaimed = {p.name for p in out.iterdir()} - OWNED - FOREIGN - KEEP
    if unclaimed:
        raise SystemExit(
            f"unclaimed vector paths: {', '.join(sorted(unclaimed))}. Add each to "
            "OWNED (this generator prunes it) or FOREIGN (another one owns it); "
            "a path in neither escapes pruning and rots.")

    removed = []
    for name in sorted(OWNED):
        root = out / name
        for path in sorted([root] if root.is_file() else root.rglob("*")):
            if not path.is_file() or path.name in KEEP:
                continue
            if path.resolve() not in _written:
                path.unlink()
                removed.append(path)
    for name in sorted(OWNED):
        root = out / name
        if not root.is_dir():
            continue
        for folder in sorted(root.rglob("*"), reverse=True):
            if folder.is_dir() and not any(folder.iterdir()):
                folder.rmdir()
    return removed


def write_keys(out: pathlib.Path) -> None:
    doc = {
        "comment": "TEST KEYS. Seeds are SHA-256('norn/testvector/v1\\n' + name); "
                   "WireGuard keys are X25519 from SHA-256(prefix + 'wg/' + name).",
        "ed25519": {
            name: {"seed": k.seed, "public": k.public, "kid": k.id}
            for name, k in sorted(fixture.KEYS.items())
        },
        "x25519": {name: pk for name, pk in sorted(fixture.WG.items())},
        "net": fixture.NET,
    }
    write(out / "keys.json", canonjson.dumps(doc) + "\n")


def write_entries(out: pathlib.Path) -> None:
    for name, env in fixture.catalogue():
        raw = entry.encode(env)
        write(out / "entries" / f"{name}.cbor", raw)
        write(out / "entries" / f"{name}.json", canonjson.dumps({
            "entry": env,
            "entry_hash": entry.entry_hash(raw),
            "leaf_hash": entry.leaf_hash(raw),
            "preimage_sha256": hashlib.sha256(entry.preimage(env)).digest(),
            "size": len(raw),
        }) + "\n")


def write_log(out: pathlib.Path) -> None:
    """The replay fixture: the log, its manifest, and the state it produces."""
    items = fixture.log()
    raw = [item.raw for item in items]
    for item in items:
        write(out / "log" / f"{item.name}.cbor", item.raw)
        if item.reason:
            write(out / "log" / f"{item.name}.reason", item.reason + "\n")

    anchor = replay.Anchor(net=fixture.NET, genesis_hash=entry.leaf_hash(raw[0]))
    write(out / "log" / "manifest.json", canonjson.dumps({
        "anchor": {"net": anchor.net, "genesis_hash": anchor.genesis_hash},
        "entries": [{"index": i, "name": it.name, "reason": it.reason or ""}
                    for i, it in enumerate(items)],
    }) + "\n")
    final = replay.replay(anchor, raw)
    write(out / "state.json", final.to_json() + "\n")
    write_proven(out, final)


def write_proven(out: pathlib.Path, final: Any) -> None:
    """The proven set at four evaluation times (SPEC §5.3).

    `state.json` is deliberately clock-independent, so until this existed the
    suite had no vector for expiry at all -- the rule that decides when a
    device stops being admitted to the network. Cold gate run 5 named it the
    one gap with a direct production consequence.

    The deadlines are read from the state rather than written down: a fixture
    that hardcodes an instant stops testing the boundary the moment the entry
    behind it changes.
    """
    deadlines = sorted({d["expires"] for d in final.devices.values()
                        if d["status"] == "active" and d.get("expires")})
    if not deadlines:
        raise SystemExit("no active device has an expiry; the proven fixture would prove nothing")
    deadline = deadlines[0]

    cases = [
        (0, "no-clock",
         "no instant satisfies the witness policy, so expiry is not judged at all"),
        (deadline - 1, "before-the-deadline", "one second before it expires"),
        (deadline, "at-the-deadline",
         "expires == T has passed: the boundary two implementations disagree about"),
        (deadline + 1, "after-the-deadline", "one second after"),
    ]
    write(out / "proven" / "cases.json", canonjson.dumps({
        "comment": "the devices a node admits at evaluation time `t` (SPEC §5.3). "
                   "`t` is the checkpoint's quorum time, never a wall clock, and "
                   "t = 0 means there is no clock at all. A device is expired "
                   "exactly when expires != 0 and expires <= t",
        "cases": [{"name": name, "t": t, "why": why, "proven": final.proven(t)}
                  for t, name, why in cases],
    }) + "\n")


def write_genesis_aborts(out: pathlib.Path) -> None:
    """Every way entry 0 can abort replay, one single-entry log per case."""
    index = []
    for name, raw, anchor in fixture.genesis_aborts():
        folder = out / "genesis" / name
        write(folder / "00-genesis.cbor", raw)
        write(folder / "manifest.json", canonjson.dumps({
            "anchor": {"net": anchor.net, "genesis_hash": anchor.genesis_hash},
            "entries": [{"index": 0, "name": "00-genesis", "reason": "bad-genesis"}],
        }) + "\n")
        write(folder / "state.json", replay.replay(anchor, [raw]).to_json() + "\n")
        index.append(name)
    write(out / "genesis" / "cases.json", canonjson.dumps({
        "comment": "each subdirectory is a one-entry log whose replay MUST abort "
                   "with bad-genesis; an abort stops replay, so cases cannot share a log",
        "cases": index,
    }) + "\n")


def write_trust_rejections(out: pathlib.Path) -> None:
    """Trust files a verifier MUST refuse (SPEC §9.1)."""
    cases = []
    for name, doc in fixture.trust_rejections():
        write(out / "trust-bad" / f"{name}.cbor", trust.encode(doc))
        cases.append(name)
    write(out / "trust-bad" / "cases.json", canonjson.dumps({
        "comment": "every file here MUST be refused as a trust anchor -- by the "
                   "CBOR schema of SPEC 9.1 or by validation, whichever owns the "
                   "rule; the file name says which rule it is about",
        "cases": cases,
    }) + "\n")


def write_empty_log(out: pathlib.Path) -> None:
    """§5.1: replay of an EMPTY list yields the zero state (run 8, D19).

    "There is nothing to reject" -- so `size` is 0 and `rejected` is empty,
    which is not the same as `bad-genesis`. Every log in the suite had at least
    one entry, so `empty-log-is-bad-genesis` reproduced everything.
    """
    from nornref import replay as replaymod
    anchor = replaymod.Anchor(fixture.NET, entry.leaf_hash(
        entry.encode(fixture.genesis())))
    state = replaymod.replay(anchor, [])
    write(out / "log-empty" / "manifest.json", canonjson.dumps({
        "anchor": {"net": fixture.NET, "genesis_hash": anchor.genesis_hash},
        "entries": [],
        "comment": "a log with no entries at all. SPEC 5.1: replay yields the "
                   "zero state -- size 0, `rejected` empty -- and NOT a "
                   "`bad-genesis` abort, because there is nothing to reject",
    }) + "\n")
    write(out / "log-empty" / "state.json", state.to_json() + "\n")


def write_trust_acceptances(out: pathlib.Path) -> None:
    """Trust files §9.1 permits (cold gate run 8, D22).

    A reader that requires an optional member refuses files this document
    allows, and only a positive shows it.
    """
    cases = []
    for name, doc in fixture.trust_acceptances():
        trust.validate(doc)  # the oracle: a case that does not validate is a bug
        write(out / "trust-good" / f"{name}.cbor", trust.encode(doc))
        cases.append(name)
    write(out / "trust-good" / "cases.json", canonjson.dumps({
        "comment": "every file here MUST be accepted as a trust anchor. Each "
                   "exercises a member SPEC 9.1 marks optional, or a value it "
                   "leaves open: a reader that requires a witness `url`, or "
                   "refuses an `anchor` type it does not recognise, rejects "
                   "files this document permits",
        "cases": cases,
    }) + "\n")


def write_trust(out: pathlib.Path) -> None:
    """The trust anchor, its human rendering, its fingerprint, and a receipt."""
    doc = fixture.trust_file()
    trust.validate(doc)
    write(out / "trust.cbor", trust.encode(doc))
    write(out / "trust.toml", trust.to_toml(doc))
    write(out / "trust.fingerprint", trust.fingerprint(doc) + "\n")

    genesis_leaf = doc["genesis_hash"]
    deadline = fixture.T0 + 60  # params.mmd
    text = note.receipt_text(doc["origin"], genesis_leaf, deadline)
    signed = note.sign(text, doc["origin"], fixture.KEYS["logkey"])
    write(out / "receipt.note", signed)
    write(out / "receipt.json", canonjson.dumps({
        "comment": "receipt for the genesis entry; verifies under trust.log_key",
        "origin": doc["origin"],
        "leaf_hash": genesis_leaf,
        "deadline": deadline,
        "text_sha256": __import__("hashlib").sha256(text.encode()).digest(),
    }) + "\n")


def write_policies(out: pathlib.Path) -> None:
    """§9.1's restated grammar, both sides of each rule (cold gate run 8, D12)."""
    from nornref import policy as policymod
    evaluations = fixture.policy_evaluations()
    cases = []
    for name, text, accept, why in fixture.policy_grammar():
        # The oracle is the reference parser: a case that does not behave as
        # its own table says is a generator bug, not a vector.
        try:
            policymod.parse(text)
            parsed = True
        except policymod.PolicyError:
            parsed = False
        if parsed != accept:
            raise SystemExit(
                f"policy case {name}: table says accept={accept}, parser says {parsed}")
        write(out / "policies" / f"{name}.txt", text.encode())
        case = {"name": name, "accept": accept, "why": why}
        if evaluations.get(name):
            case["evaluate"] = evaluations[name]
        cases.append(case)
    write(out / "policies" / "cases.json", canonjson.dumps({
        "comment": "SPEC 9.1's restated `tlog-policy` grammar, one whole policy "
                   "per rule, each differing from a valid one in exactly one way. "
                   "A case with `accept` true MUST parse; the rest MUST be "
                   "refused. The text is the file verbatim -- some cases turn on "
                   "whether it ends in a newline. A case with `evaluate` also "
                   "says what its quorum MEANS: each entry gives a set of "
                   "cosigner names and whether they satisfy it, which is the "
                   "only way a reader's arithmetic can be checked",
        "cases": cases,
    }) + "\n")


def write_requests(out: pathlib.Path) -> None:
    """Enrollment requests and the requests a signer MUST refuse (SPEC §16).

    The negatives are shipped as *text* because that is the form a signer is
    handed -- a QR or a pasted string -- and because four of them are faults in
    the text layer itself, which a CBOR-only vector could not express.
    """
    def emit(name: str, req: dict, text: str) -> None:
        raw = enrollreq.encode(req)
        write(out / "requests" / f"{name}.cbor", raw)
        write(out / "requests" / f"{name}.txt", text + "\n")
        write(out / "requests" / f"{name}.json", canonjson.dumps({
            "request": req,
            "preimage_sha256": hashlib.sha256(enrollreq.preimage(req)).digest(),
            "text": text,
            "size": len(raw),
        }) + "\n")

    cases = []
    for name, req in fixture.enroll_requests():
        emit(name, req, enrollreq.to_text(req))
        cases.append({"name": name, "form": "canonical"})

    # Cold-model gate run 7, defect J6. SPEC 16.2: "The canonical form is
    # lowercase. An all-uppercase form MUST also be accepted, because QR
    # alphanumeric mode has no lowercase letters and a request is meant to
    # cross a room on a phone screen." Every request here was lowercase and
    # `requests-bad/` holds only negatives, so the one *positive* obligation in
    # 16.2 -- the one the whole enrolment flow rests on -- was pinned by
    # nothing, and `bech32-reject-upper` passed the entire suite.
    twin, req = fixture.enroll_requests()[0]
    emit(f"{twin}-upper", req, enrollreq.to_text(req).upper())
    cases.append({"name": f"{twin}-upper", "form": "uppercase",
                  "same_request_as": twin})

    write(out / "requests" / "cases.json", canonjson.dumps({
        "comment": "each case is one enrollment request: .cbor is the request, "
                   ".txt its bech32m form with a trailing newline, .json its "
                   "fields and the SHA-256 of its signature preimage. `form` "
                   "is `canonical` for the lowercase form SPEC 16.2 defines, "
                   "and `uppercase` for the same request in the form 16.2 says "
                   "a reader MUST also accept; an uppercase case names the "
                   "canonical one it duplicates, and only its .txt differs",
        "cases": cases,
    }) + "\n")

    bad = []
    for name, text, why in fixture.request_negatives():
        write(out / "requests-bad" / f"{name}.txt", text + "\n")
        bad.append({"name": name, "why": why,
                    "signature": _signature_state(name, text)})
    write(out / "requests-bad" / "cases.json", canonjson.dumps({
        "comment": "every .txt here MUST be refused, whether by the text layer, "
                   "the CBOR profile, a field rule or signature verification; "
                   "each file has a trailing newline that is not part of the case",
        "cases": bad,
    }) + "\n")


    hostile = []
    for name, raw, says in fixture.hostile_inputs():
        write(out / "entries-hostile" / f"{name}.cbor", raw)
        if says is None:
            # A case sitting exactly at a limit: it must be accepted, and it
            # is what bounds the limit from below.
            hostile.append({"name": name, "accepted": True})
        else:
            hostile.append({"name": name, "says": says})
    write(out / "entries-hostile" / "cases.json", canonjson.dumps({
        "comment": "input at and past SPEC 4.0's resource limits: a case with `says` MUST be "
                   "refused for that reason, and a case marked `accepted` sits exactly at a limit "
                   "and MUST be accepted, which is what bounds it from below. Neither limit is "
                   "reachable by a valid entry, so these are the only vectors that reach them",
        "cases": hostile,
    }) + "\n")


#: The two negatives the strict decoder cannot read, and why each is
#: nonetheless signed over the bytes that ship. Named individually because a
#: blanket answer here is how the whole class went unchecked.
_PROFILE_CASE_SIGNATURES = {
    # Re-signed over the patched preimage in 6.5c: the 24-byte key cannot
    # canonicalise away, so SPEC 4.0's second construction route applies.
    "oversize-label-key": "valid",
    # The patch swaps two map entries, which canonicalises away when the
    # preimage is re-encoded, so the original signature still covers it --
    # SPEC 4.0's first construction route.
    "unsorted-keys": "valid",
    # SPEC 16.2 text-layer cases: the payload is the valid request's bytes with
    # its *encoding* corrupted, so the request inside is signed correctly and
    # the fault is in the wrapper, not in any field rule.
    "excess-padding": "valid",
    "non-zero-padding": "valid",
}


def _signature_state(name: str, text: str) -> str:
    """Whether this negative's `sig` covers the bytes that ship.

    Computed, not declared. A negative that names a field rule and carries a
    stale signature is refused by Ed25519 before its rule is reached, and
    eleven of fifteen were, because nobody had asked the question per case.
    """
    from nornref import bech32m, cbor, enrollreq, keys as keymod

    try:
        _, raw = bech32m.decode(text)
    except Exception:
        # A text-layer case: the wrapper is the fault and the bytes inside are
        # the valid request, signature and all.
        return "valid"
    try:
        req = cbor.decode(raw)
    except cbor.ProfileError:
        if name in _PROFILE_CASE_SIGNATURES:
            return _PROFILE_CASE_SIGNATURES[name]
        raise SystemExit(
            f"{name}: outside the CBOR profile and not accounted for; say whether its "
            "signature covers its own bytes and why")
    sig, public = req.get("sig"), req.get("device_pk")
    if not isinstance(sig, bytes) or len(sig) != 64 or not isinstance(public, bytes):
        return "broken"
    return "valid" if keymod.verify(public, enrollreq.preimage(req), sig) else "broken"


def main(argv: list[str]) -> int:
    out = pathlib.Path(argv[1] if len(argv) > 1 else "testdata/vectors")
    write_keys(out)
    write_entries(out)
    write_log(out)
    write_genesis_aborts(out)
    write_trust_rejections(out)
    write_trust_acceptances(out)
    write_empty_log(out)
    write_trust(out)
    write_policies(out)
    write_requests(out)
    removed = prune(out)
    for path in removed:
        print(f"pruned stale {path.relative_to(out)}")
    count = sum(1 for _ in out.rglob("*") if _.is_file())
    print(f"wrote {count} files to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
